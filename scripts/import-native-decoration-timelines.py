#!/usr/bin/env python3
"""Export the four animated Shop decorations from the pinned client, preserving their meshes.

Static Shop portraits remain the output of import-native-decorations.py. This exporter keeps
the original base/body timelines and crops only unused atlas borders, using the same pinned
reader and native graph builder. Run with --check to reproduce every generated byte.
"""
import argparse
import importlib.util
import io
import json
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KINDS = ('torch', 'white-flag', 'windmeter', 'skull-flag')


def importer():
    spec = importlib.util.spec_from_file_location(
        'decoration_source', ROOT / 'scripts/import-native-decorations.py')
    source = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(source)
    return source


def build():
    source = importer()
    renderer = source.compositor()
    from native_art.sc6 import decode_sctx, require
    from native_art.scene_graph import crop_textures
    from native_art.bundle import digest

    catalog = json.loads((ROOT / 'reference/decorations/catalog.json').read_text())
    definitions = {row['id']: row for row in catalog['decorations']}
    scene = renderer.scene('sc/buildings.sc')

    @lru_cache(maxsize=8)
    def texture(index):
        return decode_sctx(source.read(f'sc/buildings_{index}.sctx'))

    files, entries = {}, {}
    for kind in KINDS:
        definition = definitions[kind]
        exports = [definition['base'], definition['export']]
        graph = renderer.graph_for(scene, exports)
        animated = {
            key: dict(fps=clip['fps'], frames=len(clip['timeline']))
            for key, clip in graph['clips'].items() if len(clip['timeline']) > 1
        }
        require(bool(animated), f'{kind} has no native animation')
        used = {index for commands in graph['shapes'].values() for index, _ in commands}
        prefix = f'assets/decorations-native/{kind}'
        images, _, runtime = crop_textures(
            graph, {index: texture(index) for index in used}, f'{prefix}/buildings')
        textures = {}
        for relative, image in images.items():
            encoded = io.BytesIO()
            image.save(encoded, format='PNG', optimize=True)
            files[ROOT / 'public' / relative] = encoded.getvalue()
            textures[relative] = dict(width=image.width, height=image.height,
                                      rgbaSha256=digest(image.tobytes()))
        pack = dict(kind=kind, base=definition['base'], body=definition['export'],
                    scenes=dict(buildings=runtime))
        path = f'{prefix}/graph.json'
        data = (json.dumps(pack, separators=(',', ':')) + '\n').encode()
        files[ROOT / 'public' / path] = data
        entries[kind] = dict(path=path, sha256=digest(data), animatedClips=animated,
                             textures=textures)
    index = dict(clientVersion=catalog['clientVersion'], bundle=catalog['bundle'],
                 sources=dict(sorted(source.USED.items())), decorations=entries)
    files[ROOT / 'reference/decorations/timelines.json'] = (
        json.dumps(index, indent=2) + '\n').encode()
    return files, index


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--report', action='store_true', help='Measure without writing artifacts')
    args = parser.parse_args()
    files, index = build()
    for path, data in files.items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'Decoration timelines differ: {path.relative_to(ROOT)}')
        elif not args.report:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for kind, entry in index['decorations'].items():
        pixels = sum(row['width'] * row['height'] for row in entry['textures'].values())
        encoded = sum(len(files[ROOT / 'public' / path]) for path in entry['textures'])
        print(f'{kind}: {len(entry["animatedClips"])} animated clips, '
              f'{pixels * 4:,} decoded RGBA bytes, {encoded:,} PNG bytes')
    print('Decoration timelines reproduce the pinned client.' if args.check else
          'Decoration timeline report complete.' if args.report else
          'Wrote native decoration timelines and source index.')


if __name__ == '__main__':
    main()
